// providers/trending_provider.dart — Trending v2 (ChangeNotifier provider)

import 'package:flutter/foundation.dart';
import '../gateways/trending_gateway.dart';
import '../models/trending.dart';

class TrendingProvider extends ChangeNotifier {
  final TrendingGateway gateway;

  TrendingProvider({required TrendingGateway gateway}) : gateway = gateway;

  // ── State ──

  TrendingFeed? _feed;
  TrendingPipelineStatus? _pipelineStatus;
  List<TrendingProfile> _archive = [];
  List<TrendingChallenge> _activeChallenges = [];
  TrendingSortOption _sortOption = TrendingSortOption.trendScore;

  bool _isLoading = false;
  bool _isRefreshing = false;
  bool _isLoadingArchive = false;
  String? _error;

  // ── Getters ──

  TrendingFeed? get feed => _feed;
  TrendingPipelineStatus? get pipelineStatus => _pipelineStatus;
  List<TrendingProfile> get archive => _archive;
  List<TrendingChallenge> get activeChallenges => _activeChallenges;
  TrendingSortOption get sortOption => _sortOption;

  bool get isLoading => _isLoading;
  bool get isRefreshing => _isRefreshing;
  bool get isLoadingArchive => _isLoadingArchive;
  String? get error => _error;

  List<TrendingProfile> get sortedProfiles {
    if (_feed == null) return [];
    final profiles = List<TrendingProfile>.from(_feed!.profiles);
    switch (_sortOption) {
      case TrendingSortOption.trendScore:
        profiles.sort((a, b) => b.trendScore.compareTo(a.trendScore));
        break;
      case TrendingSortOption.newest:
        profiles.sort((a, b) => b.publishedAt.compareTo(a.publishedAt));
        break;
      case TrendingSortOption.expiringSoon:
        profiles.sort((a, b) => a.expiresAt.compareTo(b.expiresAt));
        break;
      case TrendingSortOption.engagement:
        profiles.sort(
            (a, b) => b.engagementScore.compareTo(a.engagementScore));
        break;
    }
    return profiles;
  }

  int get autoGeneratedCount {
    if (_feed == null) return 0;
    return _feed!.profiles.where((p) => p.isAutoGenerated).length;
  }

  int get manualCount {
    if (_feed == null) return 0;
    return _feed!.profiles.where((p) => !p.isAutoGenerated).length;
  }

  double challengeProgress(String profileId) {
    final profile = _feed?.profiles.firstWhere(
      (p) => p.id == profileId,
      orElse: () => throw Exception('Profile not found'),
    );
    if (profile == null || profile.miniChallenges.isEmpty) return 0.0;

    final completed = _activeChallenges
        .where(
          (c) =>
              profile.miniChallenges.any((mc) => mc.id == c.id) &&
              c.isCompleted,
        )
        .length;
    return completed / profile.miniChallenges.length;
  }

  // ── v1 actions ──

  Future<void> loadFeed() async {
    _isLoading = true;
    _error = null;
    notifyListeners();

    try {
      _feed = await gateway.loadTrendingFeed();
    } catch (e) {
      _error = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  Future<void> startChallenge(String profileId) async {
    try {
      await gateway.startChallenge(profileId);
      _activeChallenges = await gateway.getActiveChallenges();
      notifyListeners();
    } catch (e) {
      _error = e.toString();
      notifyListeners();
    }
  }

  Future<void> completeChallenge(
      String profileId, String challengeId) async {
    try {
      await gateway.completeChallenge(profileId, challengeId);
      _activeChallenges = await gateway.getActiveChallenges();
      notifyListeners();
    } catch (e) {
      _error = e.toString();
      notifyListeners();
    }
  }

  Future<void> dismissProfile(String id) async {
    try {
      await gateway.dismissProfile(id);
      await loadFeed();
    } catch (e) {
      _error = e.toString();
      notifyListeners();
    }
  }

  // ── v2 actions ──

  Future<void> loadPipelineStatus() async {
    try {
      _pipelineStatus = await gateway.getPipelineStatus();
      notifyListeners();
    } catch (e) {
      _error = e.toString();
      notifyListeners();
    }
  }

  Future<void> refreshFeed() async {
    _isRefreshing = true;
    notifyListeners();

    try {
      await gateway.refreshFeed();
      _feed = await gateway.loadTrendingFeed();
      _pipelineStatus = await gateway.getPipelineStatus();
    } catch (e) {
      _error = e.toString();
    } finally {
      _isRefreshing = false;
      notifyListeners();
    }
  }

  Future<void> loadArchive() async {
    _isLoadingArchive = true;
    notifyListeners();

    try {
      _archive = await gateway.loadArchive();
    } catch (e) {
      _error = e.toString();
    } finally {
      _isLoadingArchive = false;
      notifyListeners();
    }
  }

  void sortBy(TrendingSortOption option) {
    _sortOption = option;
    notifyListeners();
  }
}
