// "For you": things a person can benefit from, chosen from what they told
// ONO in the plan builder (life wheel, goal, roles, this month's area).
// Books, films, podcasts and courses go on their learning list; practices
// become daily items with a cue and a minimum; steps go into this week's
// three; tools open the part of ONO that helps.
//
// General content: nothing here names a person or employer (tested).
// Everything is real and well regarded; each says why it helps.

class Suggestion {
  final String id;

  /// The life area it serves (lib/data/life_wheel.dart).
  final String area;

  /// read | watch | listen | course | daily | step | tool.
  final String kind;
  final String title;

  /// Author, director, host or year.
  final String by;
  final String why;

  /// For daily practices.
  final String lane;
  final String when;
  final String cue;
  final String minimum;

  /// For tools: the ONO route to open.
  final String route;

  /// Shown first when the person's role or goal matches: lead, founder,
  /// parent, fitness, study.
  final List<String> tags;

  const Suggestion(this.id, this.area, this.kind, this.title, this.why,
      {this.by = '',
      this.lane = 'mind',
      this.when = 'day',
      this.cue = '',
      this.minimum = '',
      this.route = '',
      this.tags = const []});
}

