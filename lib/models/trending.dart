class TrendingChallenge {
  final String id;
  final String title;
  final String description;
  final int lane;
  final int dayNumber;
  final bool isCompleted;

  const TrendingChallenge({
    required this.id,
    required this.title,
    required this.description,
    required this.lane,
    required this.dayNumber,
    this.isCompleted = false,
  });

  TrendingChallenge copyWith({
    String? id,
    String? title,
    String? description,
    int? lane,
    int? dayNumber,
    bool? isCompleted,
  }) {
    return TrendingChallenge(
      id: id ?? this.id,
      title: title ?? this.title,
      description: description ?? this.description,
      lane: lane ?? this.lane,
      dayNumber: dayNumber ?? this.dayNumber,
      isCompleted: isCompleted ?? this.isCompleted,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'description': description,
      'lane': lane,
      'dayNumber': dayNumber,
      'isCompleted': isCompleted,
    };
  }

  factory TrendingChallenge.fromJson(Map<String, dynamic> json) {
    return TrendingChallenge(
      id: json['id'] as String,
      title: json['title'] as String,
      description: json['description'] as String,
      lane: json['lane'] as int,
      dayNumber: json['dayNumber'] as int,
      isCompleted: json['isCompleted'] as bool? ?? false,
    );
  }
}

class TrendingProfile {
  final String id;
  final String name;
  final String emoji;
  final String title;
  final TrendingReason trendingReason;
  final String reasonText;
  final List<TrendingChallenge> miniChallenges;
  final DateTime publishedAt;
  final DateTime expiresAt;
  final String? imageUrl;
  final List<String> tags;
  final int viewCount;
  final double engagementScore;

  // v2 fields
  final bool isAutoGenerated;
  final String? sourceUrl;
  final String? sourcePlatform;
  final double trendScore;
  final DateTime? lastRefreshedAt;

  const TrendingProfile({
    required this.id,
    required this.name,
    required this.emoji,
    required this.title,
    required this.trendingReason,
    required this.reasonText,
    required this.miniChallenges,
    required this.publishedAt,
    required this.expiresAt,
    this.imageUrl,
    this.tags = const [],
    this.viewCount = 0,
    this.engagementScore = 0.0,
    this.isAutoGenerated = false,
    this.sourceUrl,
    this.sourcePlatform,
    this.trendScore = 0.0,
    this.lastRefreshedAt,
  });

  TrendingSource? get source {
    if (sourcePlatform == null) return null;
    try {
      return TrendingSource.values.firstWhere(
        (s) => s.name == sourcePlatform,
      );
    } catch (_) {
      return null;
    }
  }

  Duration get timeUntilExpiry => expiresAt.difference(DateTime.now());
  bool get isExpired => DateTime.now().isAfter(expiresAt);

  TrendingProfile copyWith({
    String? id,
    String? name,
    String? emoji,
    String? title,
    TrendingReason? trendingReason,
    String? reasonText,
    List<TrendingChallenge>? miniChallenges,
    DateTime? publishedAt,
    DateTime? expiresAt,
    String? imageUrl,
    List<String>? tags,
    int? viewCount,
    double? engagementScore,
    bool? isAutoGenerated,
    String? sourceUrl,
    String? sourcePlatform,
    double? trendScore,
    DateTime? lastRefreshedAt,
  }) {
    return TrendingProfile(
      id: id ?? this.id,
      name: name ?? this.name,
      emoji: emoji ?? this.emoji,
      title: title ?? this.title,
      trendingReason: trendingReason ?? this.trendingReason,
      reasonText: reasonText ?? this.reasonText,
      miniChallenges: miniChallenges ?? this.miniChallenges,
      publishedAt: publishedAt ?? this.publishedAt,
      expiresAt: expiresAt ?? this.expiresAt,
      imageUrl: imageUrl ?? this.imageUrl,
      tags: tags ?? this.tags,
      viewCount: viewCount ?? this.viewCount,
      engagementScore: engagementScore ?? this.engagementScore,
      isAutoGenerated: isAutoGenerated ?? this.isAutoGenerated,
      sourceUrl: sourceUrl ?? this.sourceUrl,
      sourcePlatform: sourcePlatform ?? this.sourcePlatform,
      trendScore: trendScore ?? this.trendScore,
      lastRefreshedAt: lastRefreshedAt ?? this.lastRefreshedAt,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'name': name,
      'emoji': emoji,
      'title': title,
      'trendingReason': trendingReason.name,
      'reasonText': reasonText,
      'miniChallenges': miniChallenges.map((c) => c.toJson()).toList(),
      'publishedAt': publishedAt.toIso8601String(),
      'expiresAt': expiresAt.toIso8601String(),
      'imageUrl': imageUrl,
      'tags': tags,
      'viewCount': viewCount,
      'engagementScore': engagementScore,
      'isAutoGenerated': isAutoGenerated,
      'sourceUrl': sourceUrl,
      'sourcePlatform': sourcePlatform,
      'trendScore': trendScore,
      'lastRefreshedAt': lastRefreshedAt?.toIso8601String(),
    };
  }

  factory TrendingProfile.fromJson(Map<String, dynamic> json) {
    return TrendingProfile(
      id: json['id'] as String,
      name: json['name'] as String,
      emoji: json['emoji'] as String,
      title: json['title'] as String,
      trendingReason: TrendingReason.values.firstWhere(
        (r) => r.name == json['trendingReason'],
      ),
      reasonText: json['reasonText'] as String,
      miniChallenges: (json['miniChallenges'] as List)
          .map((c) => TrendingChallenge.fromJson(c as Map<String, dynamic>))
          .toList(),
      publishedAt: DateTime.parse(json['publishedAt'] as String),
      expiresAt: DateTime.parse(json['expiresAt'] as String),
      imageUrl: json['imageUrl'] as String?,
      tags: (json['tags'] as List?)?.cast<String>() ?? [],
      viewCount: json['viewCount'] as int? ?? 0,
      engagementScore: (json['engagementScore'] as num?)?.toDouble() ?? 0.0,
      isAutoGenerated: json['isAutoGenerated'] as bool? ?? false,
      sourceUrl: json['sourceUrl'] as String?,
      sourcePlatform: json['sourcePlatform'] as String?,
      trendScore: (json['trendScore'] as num?)?.toDouble() ?? 0.0,
      lastRefreshedAt: json['lastRefreshedAt'] != null
          ? DateTime.parse(json['lastRefreshedAt'] as String)
          : null,
    );
  }
}

class TrendingFeed {
  final List<TrendingProfile> profiles;
  final DateTime lastUpdatedAt;

  const TrendingFeed({
    required this.profiles,
    required this.lastUpdatedAt,
  });

  TrendingFeed copyWith({
    List<TrendingProfile>? profiles,
    DateTime? lastUpdatedAt,
  }) {
    return TrendingFeed(
      profiles: profiles ?? this.profiles,
      lastUpdatedAt: lastUpdatedAt ?? this.lastUpdatedAt,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'profiles': profiles.map((p) => p.toJson()).toList(),
      'lastUpdatedAt': lastUpdatedAt.toIso8601String(),
    };
  }

  factory TrendingFeed.fromJson(Map<String, dynamic> json) {
    return TrendingFeed(
      profiles: (json['profiles'] as List)
          .map((p) => TrendingProfile.fromJson(p as Map<String, dynamic>))
          .toList(),
      lastUpdatedAt: DateTime.parse(json['lastUpdatedAt'] as String),
    );
  }
}

class TrendingPipelineStatus {
  final DateTime? lastRunAt;
  final DateTime? nextRunAt;
  final int profilesGenerated;
  final int profilesPublished;
  final bool isRunning;
  final String? lastError;

  const TrendingPipelineStatus({
    this.lastRunAt,
    this.nextRunAt,
    this.profilesGenerated = 0,
    this.profilesPublished = 0,
    this.isRunning = false,
    this.lastError,
  });

  TrendingPipelineStatus copyWith({
    DateTime? lastRunAt,
    DateTime? nextRunAt,
    int? profilesGenerated,
    int? profilesPublished,
    bool? isRunning,
    String? lastError,
  }) {
    return TrendingPipelineStatus(
      lastRunAt: lastRunAt ?? this.lastRunAt,
      nextRunAt: nextRunAt ?? this.nextRunAt,
      profilesGenerated: profilesGenerated ?? this.profilesGenerated,
      profilesPublished: profilesPublished ?? this.profilesPublished,
      isRunning: isRunning ?? this.isRunning,
      lastError: lastError ?? this.lastError,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'lastRunAt': lastRunAt?.toIso8601String(),
      'nextRunAt': nextRunAt?.toIso8601String(),
      'profilesGenerated': profilesGenerated,
      'profilesPublished': profilesPublished,
      'isRunning': isRunning,
      'lastError': lastError,
    };
  }

  factory TrendingPipelineStatus.fromJson(Map<String, dynamic> json) {
    return TrendingPipelineStatus(
      lastRunAt: json['lastRunAt'] != null
          ? DateTime.parse(json['lastRunAt'] as String)
          : null,
      nextRunAt: json['nextRunAt'] != null
          ? DateTime.parse(json['nextRunAt'] as String)
          : null,
      profilesGenerated: json['profilesGenerated'] as int? ?? 0,
      profilesPublished: json['profilesPublished'] as int? ?? 0,
      isRunning: json['isRunning'] as bool? ?? false,
      lastError: json['lastError'] as String?,
    );
  }
}
